export function isLanguage(value: unknown): value is Language {
  return languages.some(language => language.code === value);
}

export function resolveLanguage(locales: readonly (string | null)[]): Language {
  for (const locale of locales) {
    const code = locale?.split(/[-_]/)[0].toLowerCase();
    if (isLanguage(code)) return code;
  }
  return 'en';
}

export function translate(language: string, key: MessageKey, values?: Record<string, string>): string {
  const text = (isLanguage(language) ? messages[language][key] : undefined) || messages.en[key];
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => values?.[name] ?? placeholder);
}

export function languageDirection(language: string): 'rtl' | 'ltr' {
  return language === 'ur' ? 'rtl' : 'ltr';
}
